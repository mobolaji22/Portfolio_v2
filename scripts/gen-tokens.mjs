// design/tokens.json -> app/tokens.css (variables, type styles). Run: node scripts/gen-tokens.mjs
import fs from "node:fs";
const t = JSON.parse(fs.readFileSync("design/tokens.json", "utf8"));
const cssName = (k) => "--c-" + k.replace(/\./g, "-");
const vars = (theme) => {
  const base = { ...t.color[theme], ...t.color.generated[theme] };
  return Object.entries(base).map(([k, v]) => `  ${cssName(k)}: ${v};`).join("\n");
};
const fam = (f) =>
  f.startsWith("Newsreader") ? "var(--font-display), 'Times New Roman', serif"
  : f.startsWith("Instrument") ? "var(--font-ui), Arial, sans-serif"
  : f.startsWith("IBM") ? "var(--font-mono), 'Courier New', monospace"
  : "var(--font-gen), Arial, sans-serif";
const scale = Object.entries(t.spacing.px).map(([k, v]) => `  --space-${k}: ${v}px;`).join("\n");
const radius = Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}${typeof v === "number" ? "px" : ""};`).join("\n");
const dur = Object.entries(t.motion.durationMs).map(([k, v]) => `  --dur-${k}: ${v}ms;`).join("\n");
const ease = `  --ease-out: ${t.motion.easing.out};\n  --ease-in-out: ${t.motion.easing.inOut};`;
const styles = Object.entries(t.type.styles).map(([k, s]) =>
`.t-${k} { font-family: ${fam(s.family)}; font-weight: ${s.weight}; font-size: ${s.fluid}; line-height: ${s.lineHeight}; letter-spacing: ${s.letterSpacing}; }`).join("\n");
const gstyles = Object.entries(t.type.generated).map(([k, s]) =>
`.t-${k} { font-family: ${fam(s.family)}; font-weight: ${s.weight}; font-size: ${s.sizePx}px; line-height: ${s.lineHeight}; letter-spacing: ${s.letterSpacing}; }`).join("\n");
const out = `/* GENERATED by scripts/gen-tokens.mjs from design/tokens.json. Do not hand-edit. */
:root {
${vars("light")}
${scale}
${radius}
${dur}
${ease}
  --e1: ${t.elevation["e1-light"].value};
  --g-card-shadow: ${t.elevation["g-card-light"].value};
}
@media (prefers-color-scheme: dark) {
  :root:not(.light):not(.dark) {
${vars("dark")}
    --e1: ${t.elevation["e1-dark"].value};
    --g-card-shadow: ${t.elevation["g-card-dark"].value};
  }
}
:root.dark {
${vars("dark")}
  --e1: ${t.elevation["e1-dark"].value};
  --g-card-shadow: ${t.elevation["g-card-dark"].value};
}

${styles}
${gstyles}
`;
fs.writeFileSync("app/tokens.css", out);
console.log("app/tokens.css", out.length);
